"""Pixel-level, label-preserving background intervention for Waterbirds.

Waterbirds was generated by the official ``generate_waterbirds.py`` script as

    composite = round(cub * seg) + round(crop_and_resize(place, size) * (1 - seg))

with ``seg = segmentation_png / 255`` a *soft* matte in [0, 1] (the CUB mattes
average up to five annotators, so ~5% of pixels sit strictly between 0 and 1).

We invert that composition exactly:

1.  ``bg_src`` -- the source image's own Places background.  Outside the matte
    support it is present verbatim in the composite; inside it we fill with
    Telea inpainting.  Only the *rim* estimate matters (see step 2).
2.  ``bird = clip(composite - round(bg_src * (1 - seg)), 0, 255) * [seg > 0]``.
    Where ``seg == 1`` this is exactly ``cub``; where ``seg == 0`` it is exactly
    zero; only the thin ``0 < seg < 1`` rim depends on the ``bg_src`` estimate,
    and there the inpainted value is taken one to three pixels from real
    background, where Telea is most accurate.
3.  ``new = bird + round(crop_and_resize(bg_donor, size) * (1 - seg))`` for a
    donor background of the requested type.

Donor backgrounds are themselves recovered from *training-split* Waterbirds
images by inpainting the donor's own bird hole, so no Places365 download is
needed.  Donors are restricted to small-bird images, and the fraction of final
pixels that are visibly inpainted is recorded for every generated image.

The bird foreground, the matte, and the label are identical across arms; only
the background pixels change.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

from common import Metadata, derive_seed, mask_path, image_path

RESAMPLE = Image.Resampling.LANCZOS


# --------------------------------------------------------------------------- #
# Geometry (faithful port of group_DRO/dataset_scripts/dataset_utils.py)
# --------------------------------------------------------------------------- #
def crop_and_resize(source_img: Image.Image, target_size: tuple[int, int]) -> Image.Image:
    """Make ``source_img`` exactly ``target_size`` by expanding/shrinking then centre-cropping."""
    source_width, source_height = source_img.size
    target_width, target_height = target_size

    if (source_width < target_width) or (source_height < target_height):
        width_resize = (target_width, int((target_width / source_width) * source_height))
        if (width_resize[0] >= target_width) and (width_resize[1] >= target_height):
            source_resized = source_img.resize(width_resize, RESAMPLE)
        else:
            height_resize = (int((target_height / source_height) * source_width), target_height)
            source_resized = source_img.resize(height_resize, RESAMPLE)
        return crop_and_resize(source_resized, target_size)

    source_aspect = source_width / source_height
    target_aspect = target_width / target_height
    if source_aspect > target_aspect:
        new_source_width = int(target_aspect * source_height)
        offset = (source_width - new_source_width) // 2
        box = (offset, 0, source_width - offset, source_height)
    else:
        new_source_height = int(source_width / target_aspect)
        offset = (source_height - new_source_height) // 2
        box = (0, offset, source_width, source_height - offset)
    return source_img.crop(box).resize((target_width, target_height), RESAMPLE)


# --------------------------------------------------------------------------- #
# Matte handling
# --------------------------------------------------------------------------- #
def load_matte(path: str | Path) -> np.ndarray:
    """Soft CUB matte as float64 HxWx1 in [0, 1]."""
    seg = np.asarray(Image.open(path).convert("L"), dtype=np.float64) / 255.0
    return seg[:, :, None]


def hole_mask(seg: np.ndarray, dilate: int = 2) -> np.ndarray:
    """uint8 {0,255} mask of every pixel the bird touches at all, slightly dilated."""
    raw = (seg[:, :, 0] > 0.0).astype(np.uint8) * 255
    if dilate > 0:
        kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * dilate + 1, 2 * dilate + 1))
        raw = cv2.dilate(raw, kernel)
    return raw


def recover_background(rgb: np.ndarray, seg: np.ndarray, inpaint_radius: int, dilate: int = 2) -> tuple[np.ndarray, np.ndarray]:
    """Places background of a composite: verbatim outside the matte, inpainted inside.

    Returns ``(background_uint8, hole_uint8)``.
    """
    hole = hole_mask(seg, dilate=dilate)
    bgr = cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR)
    filled = cv2.inpaint(bgr, hole, inpaint_radius, cv2.INPAINT_TELEA)
    return cv2.cvtColor(filled, cv2.COLOR_BGR2RGB), hole


def extract_bird_layer(rgb: np.ndarray, seg: np.ndarray, bg_src: np.ndarray) -> np.ndarray:
    """Premultiplied bird layer ``round(cub * seg)`` recovered from the composite."""
    background_term = np.round(bg_src.astype(np.float64) * (1.0 - seg))
    bird = np.clip(rgb.astype(np.float64) - background_term, 0.0, 255.0)
    return bird * (seg > 0.0)


def recompose(bird_layer: np.ndarray, seg: np.ndarray, new_background: np.ndarray) -> np.ndarray:
    """Official composition rule with a new background."""
    combined = bird_layer + np.round(new_background.astype(np.float64) * (1.0 - seg))
    return np.clip(combined, 0.0, 255.0).astype(np.uint8)


# --------------------------------------------------------------------------- #
# Donor bank
# --------------------------------------------------------------------------- #
@dataclass
class DonorBank:
    """Clean Places backgrounds recovered from held-out training-split composites."""

    meta: Metadata
    image_root: Path
    mask_root: Path
    rows_by_place: dict[int, np.ndarray]
    inpaint_radius: int
    dilate: int
    _cache: dict[int, tuple[Image.Image, Image.Image]]

    @classmethod
    def build(
        cls,
        meta: Metadata,
        image_root: str | Path,
        mask_root: str | Path,
        foreground_fraction: np.ndarray,
        donor_split: int = 0,
        max_foreground: float = 0.08,
        inpaint_radius: int = 5,
        dilate: int = 2,
    ) -> "DonorBank":
        eligible = (meta.split == donor_split) & (foreground_fraction <= max_foreground)
        rows_by_place = {}
        for place in (0, 1):
            rows = np.flatnonzero(eligible & (meta.place == place))
            if rows.size == 0:
                raise RuntimeError(
                    f"no donor backgrounds for place={place} at max_foreground={max_foreground}"
                )
            rows_by_place[place] = rows
        return cls(
            meta=meta,
            image_root=Path(image_root),
            mask_root=Path(mask_root),
            rows_by_place=rows_by_place,
            inpaint_radius=inpaint_radius,
            dilate=dilate,
            _cache={},
        )

    def counts(self) -> dict[str, int]:
        return {f"place_{p}": int(rows.size) for p, rows in self.rows_by_place.items()}

    def _load_donor(self, row: int) -> tuple[Image.Image, Image.Image]:
        """(recovered background, hole indicator) at the donor's native resolution."""
        cached = self._cache.get(row)
        if cached is not None:
            return cached
        name = str(self.meta.img_filename[row])
        rgb = np.asarray(Image.open(image_path(self.image_root, name)).convert("RGB"), dtype=np.uint8)
        seg = load_matte(mask_path(self.mask_root, name))
        background, hole = recover_background(rgb, seg, self.inpaint_radius, self.dilate)
        pair = (Image.fromarray(background), Image.fromarray(hole))
        # Bounded: donors are full-resolution and this runs in every worker process.
        if len(self._cache) < 64:
            self._cache[row] = pair
        return pair

    def candidate_rows(self, place: int, *, source_img_id: int, arm: str, draw: int, tries: int) -> list[int]:
        rows = self.rows_by_place[int(place)]
        rng = np.random.default_rng(derive_seed("donor", source_img_id, arm, draw))
        return [int(rows[i]) for i in rng.integers(0, rows.size, size=max(1, tries))]

    def background_for(
        self,
        place: int,
        target_size: tuple[int, int],
        *,
        source_img_id: int,
        arm: str,
        draw: int,
        visible_weight: np.ndarray,
        max_visible_inpaint: float = 0.03,
        tries: int = 4,
    ) -> tuple[np.ndarray, np.ndarray, int, float]:
        """Donor background resized to ``target_size`` plus its inpainted-hole indicator.

        Up to ``tries`` donors are drawn from a fixed deterministic sequence; the
        first whose inpainted hole stays below ``max_visible_inpaint`` of the
        visible background area is taken, otherwise the best of the batch.  The
        rule depends only on matte geometry and is applied identically to both
        arms, so it cannot favour one background type over the other.
        """
        weight_sum = max(float(np.sum(visible_weight)), 1e-9)
        best: tuple[float, np.ndarray, np.ndarray, int] | None = None
        for row in self.candidate_rows(place, source_img_id=source_img_id, arm=arm, draw=draw, tries=tries):
            background, hole = self._load_donor(row)
            background_resized = np.asarray(crop_and_resize(background, target_size), dtype=np.uint8)
            hole_resized = np.asarray(crop_and_resize(hole, target_size), dtype=np.uint8) > 127
            visible = float(np.sum(visible_weight * hole_resized) / weight_sum)
            if best is None or visible < best[0]:
                best = (visible, background_resized, hole_resized, row)
            if visible <= max_visible_inpaint:
                break
        visible, background_resized, hole_resized, row = best  # type: ignore[misc]
        return background_resized, hole_resized, row, visible


# --------------------------------------------------------------------------- #
# Source-side intervention
# --------------------------------------------------------------------------- #
@dataclass
class SourceImage:
    img_id: int
    filename: str
    rgb: np.ndarray
    seg: np.ndarray
    bird_layer: np.ndarray
    place: int
    y: int

    @property
    def size(self) -> tuple[int, int]:
        return (self.rgb.shape[1], self.rgb.shape[0])

    @property
    def foreground_fraction(self) -> float:
        return float(np.mean(self.seg[:, :, 0] > 0.5))

    @property
    def rim_fraction(self) -> float:
        s = self.seg[:, :, 0]
        return float(np.mean((s > 0.0) & (s < 1.0)))


def load_source(
    meta: Metadata,
    row: int,
    image_root: str | Path,
    mask_root: str | Path,
    inpaint_radius: int = 5,
    dilate: int = 2,
) -> SourceImage:
    name = str(meta.img_filename[row])
    rgb = np.asarray(Image.open(image_path(image_root, name)).convert("RGB"), dtype=np.uint8)
    seg = load_matte(mask_path(mask_root, name))
    if seg.shape[:2] != rgb.shape[:2]:
        raise RuntimeError(f"matte/image size mismatch for {name}")
    bg_src, _ = recover_background(rgb, seg, inpaint_radius, dilate)
    bird_layer = extract_bird_layer(rgb, seg, bg_src)
    return SourceImage(
        img_id=int(meta.img_id[row]),
        filename=name,
        rgb=rgb,
        seg=seg,
        bird_layer=bird_layer,
        place=int(meta.place[row]),
        y=int(meta.y[row]),
    )


def intervene(
    source: SourceImage,
    bank: DonorBank,
    arm: str,
    draw: int,
    max_visible_inpaint: float = 0.03,
    donor_tries: int = 4,
) -> tuple[Image.Image, dict[str, float]]:
    """Build one background-swapped variant.

    ``arm='same'`` draws a fresh background of the *same* type (controls for
    compositing artifacts); ``arm='opposite'`` draws the opposite type (the
    nuisance intervention).  Bird pixels, matte and label are untouched.
    """
    if arm == "same":
        target_place = source.place
    elif arm == "opposite":
        target_place = 1 - source.place
    else:
        raise ValueError(f"unknown arm: {arm}")

    visible_weight = 1.0 - source.seg[:, :, 0]
    background, _donor_hole, donor_row, visible_inpaint = bank.background_for(
        target_place,
        source.size,
        source_img_id=source.img_id,
        arm=arm,
        draw=draw,
        visible_weight=visible_weight,
        max_visible_inpaint=max_visible_inpaint,
        tries=donor_tries,
    )
    image = recompose(source.bird_layer, source.seg, background)
    diagnostics = {
        "arm": arm,
        "draw": int(draw),
        "target_place": int(target_place),
        "donor_row": int(donor_row),
        "donor_filename": str(bank.meta.img_filename[donor_row]),
        "visible_inpaint_fraction": float(visible_inpaint),
        "foreground_fraction": source.foreground_fraction,
        "rim_fraction": source.rim_fraction,
    }
    return Image.fromarray(image), diagnostics
